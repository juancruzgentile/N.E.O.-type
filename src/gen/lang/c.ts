import { type Field, L, pascal, plural, snake, upper } from "../base";
import type { FullCtx, LangImpls } from "../concepts";

// C17: los tipos se declaran con typedef struct (PascalCase), las funciones van en snake_case y las colecciones son
// un puntero más su cantidad. bool viene de <stdbool.h> y size_t de <stddef.h>.

const ty = (f: Field) => ({ int: "int", float: "double", str: "const char *", bool: "bool" })[f.t];
/** "const char *name" y "int age": el asterisco va pegado al nombre */
const decl = (f: Field, name = snake(f.n)) => (f.t === "str" ? `const char *${name}` : `${ty(f)} ${name}`);

const names = (c: FullCtx) => ({
  E: pascal(c.ent.s),
  v: snake(c.ent.s),
  vs: snake(c.ent.p),
  n: snake(c.num.n),
  NT: ty(c.num),
  s: snake(c.str.n),
  ss: snake(plural(c.str.n)),
  b: snake(c.flag.n),
});

export const c: LangImpls = {
  sum: (ctx) => {
    const { E, vs, n, NT } = names(ctx);
    return L(`${NT} total_${n}(const ${E} *${vs}, size_t count)`,
      `{`,
      `    ${NT} total = 0;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        total += ${vs}[i].${n};`,
      `    }`,
      `    return total;`,
      `}`);
  },
  avg: (ctx) => {
    const { E, vs, n } = names(ctx);
    return L(`double average_${n}(const ${E} *${vs}, size_t count)`,
      `{`,
      `    if (count == 0) {`,
      `        return 0;`,
      `    }`,
      `    double total = 0;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        total += ${vs}[i].${n};`,
      `    }`,
      `    return total / count;`,
      `}`);
  },
  maxBy: (ctx) => {
    const { E, v, vs, n } = names(ctx);
    return L(`const ${E} *${v}_with_max_${n}(const ${E} *${vs}, size_t count)`,
      `{`,
      `    const ${E} *best = NULL;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (best == NULL || ${vs}[i].${n} > best->${n}) {`,
      `            best = &${vs}[i];`,
      `        }`,
      `    }`,
      `    return best;`,
      `}`);
  },
  minBy: (ctx) => {
    const { E, v, vs, n } = names(ctx);
    return L(`const ${E} *${v}_with_min_${n}(const ${E} *${vs}, size_t count)`,
      `{`,
      `    const ${E} *best = NULL;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (best == NULL || ${vs}[i].${n} < best->${n}) {`,
      `            best = &${vs}[i];`,
      `        }`,
      `    }`,
      `    return best;`,
      `}`);
  },
  filter: (ctx) => {
    const { E, vs, b } = names(ctx);
    return L(`size_t filter_${b}_${vs}(const ${E} *${vs}, size_t count, ${E} *out)`,
      `{`,
      `    size_t found = 0;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (${vs}[i].${b}) {`,
      `            out[found++] = ${vs}[i];`,
      `        }`,
      `    }`,
      `    return found;`,
      `}`);
  },
  count: (ctx) => {
    const { E, vs, b } = names(ctx);
    return L(`size_t count_${b}_${vs}(const ${E} *${vs}, size_t count)`,
      `{`,
      `    size_t total = 0;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (${vs}[i].${b}) {`,
      `            total++;`,
      `        }`,
      `    }`,
      `    return total;`,
      `}`);
  },
  find: (ctx) => {
    const { E, v, vs, s } = names(ctx);
    return L(`const ${E} *find_${v}_by_${s}(const ${E} *${vs}, size_t count, const char *${s})`,
      `{`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (strcmp(${vs}[i].${s}, ${s}) == 0) {`,
      `            return &${vs}[i];`,
      `        }`,
      `    }`,
      `    return NULL;`,
      `}`);
  },
  map: (ctx) => {
    const { E, v, vs, s, ss } = names(ctx);
    return L(`void ${v}_${ss}(const ${E} *${vs}, size_t count, const char **out)`,
      `{`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        out[i] = ${vs}[i].${s};`,
      `    }`,
      `}`);
  },
  sort: (ctx) => {
    const { E, vs, n } = names(ctx);
    return L(`static int compare_${n}_desc(const void *a, const void *b)`,
      `{`,
      `    const ${E} *x = a;`,
      `    const ${E} *y = b;`,
      `    return (y->${n} > x->${n}) - (y->${n} < x->${n});`,
      `}`,
      ``,
      `void sort_${vs}_by_${n}(${E} *${vs}, size_t count)`,
      `{`,
      `    qsort(${vs}, count, sizeof ${vs}[0], compare_${n}_desc);`,
      `}`);
  },
  any: (ctx) => {
    const { E, vs, n, NT } = names(ctx);
    return L(`bool any_${n}_above(const ${E} *${vs}, size_t count, ${NT} limit)`,
      `{`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (${vs}[i].${n} > limit) {`,
      `            return true;`,
      `        }`,
      `    }`,
      `    return false;`,
      `}`);
  },
  classDef: (ctx) => {
    const { E } = names(ctx);
    return L(`typedef struct {`,
      ...ctx.ent.fields.map((f) => `    ${decl(f)};`),
      `} ${E};`);
  },
  validate: (ctx) => {
    const { E, v, n } = names(ctx);
    return L(`bool validate_${n}(const ${E} *${v})`,
      `{`,
      `    if (${v}->${n} < 0) {`,
      `        fprintf(stderr, "${n} cannot be negative\\n");`,
      `        return false;`,
      `    }`,
      `    return true;`,
      `}`);
  },
  toggle: (ctx) => {
    const { E, v, b } = names(ctx);
    return L(`void toggle_${b}(${E} *${v})`,
      `{`,
      `    ${v}->${b} = !${v}->${b};`,
      `}`);
  },
  describe: (ctx) => {
    const { E, v, s, n } = names(ctx);
    const fmt = ctx.num.t === "float" ? "%.2f" : "%d";
    return L(`int describe_${v}(const ${E} *${v}, char *out, size_t size)`,
      `{`,
      `    return snprintf(out, size, "${E}: %s (${fmt})", ${v}->${s}, ${v}->${n});`,
      `}`);
  },
  sumIf: (ctx) => {
    const { E, vs, n, NT, b } = names(ctx);
    return L(`${NT} total_${n}_of_${b}_${vs}(const ${E} *${vs}, size_t count)`,
      `{`,
      `    ${NT} total = 0;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (${vs}[i].${b}) {`,
      `            total += ${vs}[i].${n};`,
      `        }`,
      `    }`,
      `    return total;`,
      `}`);
  },
  page: (ctx) => {
    const { E, vs } = names(ctx);
    return L(`size_t paginate_${vs}(const ${E} *${vs}, size_t count, size_t page, size_t size, const ${E} **start)`,
      `{`,
      `    size_t first = (page - 1) * size;`,
      `    if (page == 0 || first >= count) {`,
      `        *start = NULL;`,
      `        return 0;`,
      `    }`,
      `    *start = &${vs}[first];`,
      `    return count - first < size ? count - first : size;`,
      `}`);
  },
  partition: (ctx) => {
    const { E, vs, b } = names(ctx);
    return L(`size_t partition_${vs}_by_${b}(${E} *${vs}, size_t count)`,
      `{`,
      `    size_t next = 0;`,
      `    for (size_t i = 0; i < count; i++) {`,
      `        if (${vs}[i].${b}) {`,
      `            ${E} tmp = ${vs}[next];`,
      `            ${vs}[next++] = ${vs}[i];`,
      `            ${vs}[i] = tmp;`,
      `        }`,
      `    }`,
      `    return next;`,
      `}`);
  },
  increase: (ctx) => {
    const { E, v, n, NT } = names(ctx);
    return L(`bool increase_${n}(${E} *${v}, ${NT} amount)`,
      `{`,
      `    if (amount <= 0) {`,
      `        return false;`,
      `    }`,
      `    ${v}->${n} += amount;`,
      `    return true;`,
      `}`);
  },
  fibonacci: () => L(`void fibonacci(long *out, size_t n)`,
    `{`,
    `    for (size_t i = 0; i < n; i++) {`,
    `        out[i] = i < 2 ? (long)i : out[i - 1] + out[i - 2];`,
    `    }`,
    `}`),
  factorial: () => [
    L(`unsigned long long factorial(unsigned int n)`,
      `{`,
      `    unsigned long long result = 1;`,
      `    for (unsigned int i = 2; i <= n; i++) {`,
      `        result *= i;`,
      `    }`,
      `    return result;`,
      `}`),
    L(`unsigned long long factorial(unsigned int n)`,
      `{`,
      `    return n <= 1 ? 1 : n * factorial(n - 1);`,
      `}`),
  ],
  isPrime: () => L(`bool is_prime(int n)`,
    `{`,
    `    if (n < 2) {`,
    `        return false;`,
    `    }`,
    `    for (int i = 2; i * i <= n; i++) {`,
    `        if (n % i == 0) {`,
    `            return false;`,
    `        }`,
    `    }`,
    `    return true;`,
    `}`),
  gcd: () => [
    L(`int gcd(int a, int b)`,
      `{`,
      `    return b == 0 ? a : gcd(b, a % b);`,
      `}`),
    L(`int gcd(int a, int b)`,
      `{`,
      `    while (b != 0) {`,
      `        int rest = a % b;`,
      `        a = b;`,
      `        b = rest;`,
      `    }`,
      `    return a;`,
      `}`),
  ],
  reverse: () => L(`void reverse(char *text)`,
    `{`,
    `    size_t len = strlen(text);`,
    `    for (size_t i = 0; i < len / 2; i++) {`,
    `        char tmp = text[i];`,
    `        text[i] = text[len - 1 - i];`,
    `        text[len - 1 - i] = tmp;`,
    `    }`,
    `}`),
  palindrome: () => L(`bool is_palindrome(const char *word)`,
    `{`,
    `    size_t i = 0;`,
    `    size_t j = strlen(word);`,
    `    while (i + 1 < j) {`,
    `        if (tolower((unsigned char)word[i++]) != tolower((unsigned char)word[--j])) {`,
    `            return false;`,
    `        }`,
    `    }`,
    `    return true;`,
    `}`),
  vowels: () => L(`int count_vowels(const char *text)`,
    `{`,
    `    int total = 0;`,
    `    for (const char *p = text; *p != '\\0'; p++) {`,
    `        if (strchr("aeiouAEIOU", *p) != NULL) {`,
    `            total++;`,
    `        }`,
    `    }`,
    `    return total;`,
    `}`),
  fizzbuzz: () => L(`void fizzbuzz(int n)`,
    `{`,
    `    for (int i = 1; i <= n; i++) {`,
    `        if (i % 15 == 0) {`,
    `            puts("FizzBuzz");`,
    `        } else if (i % 3 == 0) {`,
    `            puts("Fizz");`,
    `        } else if (i % 5 == 0) {`,
    `            puts("Buzz");`,
    `        } else {`,
    `            printf("%d\\n", i);`,
    `        }`,
    `    }`,
    `}`),
  binarySearch: () => L(`int binary_search(const int *items, size_t count, int target)`,
    `{`,
    `    size_t low = 0;`,
    `    size_t high = count;`,
    `    while (low < high) {`,
    `        size_t mid = low + (high - low) / 2;`,
    `        if (items[mid] == target) {`,
    `            return (int)mid;`,
    `        }`,
    `        if (items[mid] < target) {`,
    `            low = mid + 1;`,
    `        } else {`,
    `            high = mid;`,
    `        }`,
    `    }`,
    `    return -1;`,
    `}`),
  clamp: () => L(`double clamp(double value, double min, double max)`,
    `{`,
    `    return value < min ? min : value > max ? max : value;`,
    `}`),
  celsius: () => L(`double celsius_to_fahrenheit(double celsius)`,
    `{`,
    `    return celsius * 9.0 / 5.0 + 32.0;`,
    `}`),
  discount: () => L(`double apply_discount(double price, double percent)`,
    `{`,
    `    if (percent < 0 || percent > 100) {`,
    `        return price;`,
    `    }`,
    `    return price * (1 - percent / 100);`,
    `}`),
  maxValue: () => L(`int max_value(const int *numbers, size_t count)`,
    `{`,
    `    int largest = numbers[0];`,
    `    for (size_t i = 1; i < count; i++) {`,
    `        if (numbers[i] > largest) {`,
    `            largest = numbers[i];`,
    `        }`,
    `    }`,
    `    return largest;`,
    `}`),
  readFile: () => L(`char *read_file(const char *path)`,
    `{`,
    `    FILE *file = fopen(path, "rb");`,
    `    if (file == NULL) {`,
    `        perror(path);`,
    `        return NULL;`,
    `    }`,
    `    fseek(file, 0, SEEK_END);`,
    `    long size = ftell(file);`,
    `    rewind(file);`,
    `    char *text = malloc((size_t)size + 1);`,
    `    if (text != NULL) {`,
    `        size_t read = fread(text, 1, (size_t)size, file);`,
    `        text[read] = '\\0';`,
    `    }`,
    `    fclose(file);`,
    `    return text;`,
    `}`),
  enum: (ctx) => {
    const name = pascal({ w: ctx.enumSet.name });
    const prefix = upper({ w: ctx.enumSet.name });
    return L(`typedef enum {`,
      ...ctx.enumSet.values.map((v) => `    ${prefix}_${upper({ w: v })},`),
      `} ${name};`);
  },
  shape: (ctx) => {
    const s = ctx.shape;
    const T = pascal({ w: [s.name] });
    const v = s.name;
    const area = {
      circle: `3.141592653589793 * ${v}->radius * ${v}->radius`,
      rect: `${v}->width * ${v}->height`,
      square: `${v}->side * ${v}->side`,
      triangle: `${v}->base * ${v}->height / 2`,
    }[s.kind];
    return L(`typedef struct {`,
      ...s.params.map((p) => `    double ${p};`),
      `} ${T};`,
      ``,
      `double ${v}_area(const ${T} *${v})`,
      `{`,
      `    return ${area};`,
      `}`);
  },
  sumEven: () => L(`int sum_even(const int *numbers, size_t count)`,
    `{`,
    `    int total = 0;`,
    `    for (size_t i = 0; i < count; i++) {`,
    `        if (numbers[i] % 2 == 0) {`,
    `            total += numbers[i];`,
    `        }`,
    `    }`,
    `    return total;`,
    `}`),
  average: () => L(`double average(const double *numbers, size_t count)`,
    `{`,
    `    if (count == 0) {`,
    `        return 0;`,
    `    }`,
    `    double total = 0;`,
    `    for (size_t i = 0; i < count; i++) {`,
    `        total += numbers[i];`,
    `    }`,
    `    return total / count;`,
    `}`),
  capitalize: () => L(`void capitalize_words(char *text)`,
    `{`,
    `    bool start = true;`,
    `    for (char *p = text; *p != '\\0'; p++) {`,
    `        if (isspace((unsigned char)*p)) {`,
    `            start = true;`,
    `        } else if (start) {`,
    `            *p = (char)toupper((unsigned char)*p);`,
    `            start = false;`,
    `        }`,
    `    }`,
    `}`),
};
